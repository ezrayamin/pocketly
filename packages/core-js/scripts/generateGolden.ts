/**
 * Regenerates packages/core-contract/fixtures/golden.json from core-js.
 *
 * core-js is the oracle here, but it isn't trusted blindly: the Kotlin core is tested
 * against the same file (shared/src/jvmTest), so any divergence fails one of the suites.
 * Only regenerate after an intentional, reviewed algorithm change, and update both cores.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEFAULT_DATASET } from '@pocketly/core-contract';
import type { DatasetConfig } from '@pocketly/core-contract';
import { readAllTransactions } from '@pocketly/core-contract/src/testing/contractSuite';
import { JsCore } from '../src/jsCore';
import { PriceFeed } from '../src/sync/priceFeed';

const LARGE_DATASET: DatasetConfig = { ...DEFAULT_DATASET, seed: 7, transactionCount: 10_000 };
const PRICE_SYMBOLS = ['BTC', 'ETH', 'XAU', 'DOGE'];
const PRICE_SEED = 7;

async function main() {
  const core = new JsCore({ dataset: DEFAULT_DATASET });

  const defaultDataset = {
    config: DEFAULT_DATASET,
    wallet: await core.getWallet(),
    firstPage: await core.getTransactions(),
    allIds: (await readAllTransactions(core)).map((t) => t.id),
    pendingOrFailedTransferOutIds: (
      await core.getTransactions(undefined, 100, { statuses: ['PENDING', 'FAILED'], types: ['TRANSFER_OUT'] })
    ).items.map((t) => t.id),
  };

  const summaries: Record<string, unknown> = {};
  for (const month of ['2026-08', '2026-09', '2026-10', '2025-01']) {
    summaries[month] = await core.computeSpendingSummary(month);
  }

  await core.resetData(LARGE_DATASET);
  const largeDataset = {
    config: LARGE_DATASET,
    month: '2026-09',
    wallet: await core.getWallet(),
    summary: await core.computeSpendingSummary('2026-09'),
  };

  const feed = new PriceFeed(PRICE_SYMBOLS, PRICE_SEED);
  const prices = { symbols: PRICE_SYMBOLS, seed: PRICE_SEED, batches: [feed.step(), feed.step(), feed.step()] };

  // Network failure sequence (FR-DEV-03): fixed seed, 30% failure rate, 24 calls.
  const networkCore = new JsCore({ dataset: DEFAULT_DATASET });
  const simulation = { mode: 'NORMAL' as const, failureRatePercent: 30, seed: 7 };
  networkCore.setNetworkSimulation(simulation);
  const outcomes: string[] = [];
  for (let i = 0; i < 24; i++) {
    outcomes.push(await networkCore.getWallet().then(() => 'OK', (e: { code: string }) => e.code));
  }
  const network = { simulation, outcomes };

  const golden = {
    $comment: 'GENERATED by `yarn contract:golden` from core-js. Do not edit by hand.',
    defaultDataset,
    summaries,
    largeDataset,
    prices,
    network,
  };
  const out = join(__dirname, '../../core-contract/fixtures/golden.json');
  writeFileSync(out, JSON.stringify(golden, null, 2) + '\n');
  console.log(`wrote ${out}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
