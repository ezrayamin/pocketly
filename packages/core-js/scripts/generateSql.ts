/**
 * ADR-0009: one schema for both cores. Reads SQLDelight's .sq files (the single source) and
 * writes core-js/src/data/db/sql.generated.ts with the same CREATE statements and the same
 * labeled queries. Named `:params` become positional `?` plus a name order.
 *
 *   yarn sql:generate        write the file
 *   yarn sql:generate --check  fail if it's out of date (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(__dirname, '../../..');
const SOURCES = {
  SERVER: 'shared/src/commonMain/sqldelight/server/com/pocketly/shared/db/server/Server.sq',
  CACHE: 'shared/src/commonMain/sqldelight/cache/com/pocketly/shared/db/cache/Cache.sq',
} as const;
const OUT = join(ROOT, 'packages/core-js/src/data/db/sql.generated.ts');

interface Query {
  sql: string;
  /** Parameter names in positional order (named params), or the count of `?` (positional). */
  params: string[] | number;
}

function parse(source: string): { schema: string[]; queries: Record<string, Query> } {
  const text = source
    .split('\n')
    .filter((line) => !line.trim().startsWith('--'))
    .join('\n');
  const schema: string[] = [];
  const queries: Record<string, Query> = {};
  for (const raw of text.split(';')) {
    const stmt = raw.trim();
    if (!stmt) continue;
    const labeled = /^([A-Za-z][A-Za-z0-9]*):\s*\n([\s\S]+)$/.exec(stmt);
    if (!labeled) {
      schema.push(stmt.replace(/\s+/g, ' '));
      continue;
    }
    const [, label, body] = labeled;
    const names: string[] = [];
    const sql = body.replace(/\s+/g, ' ').replace(/:([A-Za-z_][A-Za-z0-9_]*)/g, (_m, name: string) => {
      names.push(name);
      return '?';
    });
    queries[label] = { sql, params: names.length > 0 ? names : (sql.match(/\?/g) ?? []).length };
  }
  return { schema, queries };
}

let out = `// GENERATED by packages/core-js/scripts/generateSql.ts from SQLDelight's .sq files (ADR-0009).
// Do not edit: change the .sq file and run \`yarn sql:generate\`.
/* eslint-disable */

export interface SqlQuery {
  readonly sql: string;
  readonly params: readonly string[] | number;
}
`;
for (const [name, path] of Object.entries(SOURCES)) {
  const { schema, queries } = parse(readFileSync(join(ROOT, path), 'utf8'));
  out += `\n/** ${path} */\nexport const ${name}_SCHEMA: readonly string[] = ${JSON.stringify(schema, null, 2)};\n`;
  out += `\nexport const ${name}_SQL = ${JSON.stringify(queries, null, 2)} as const satisfies Record<string, SqlQuery>;\n`;
}

if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8');
  if (current !== out) {
    console.error('sql.generated.ts is out of date with the .sq files. Run `yarn sql:generate`.');
    process.exit(1);
  }
  console.log('sql.generated.ts matches the .sq files');
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
